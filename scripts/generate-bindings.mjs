import { execFileSync } from "node:child_process";
import { mkdir, writeFile, readFile } from "node:fs/promises";
import { dirname } from "node:path";
import { compile } from "json-schema-to-typescript";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
const raw = execFileSync(
  "cargo",
  [
    "run",
    "--quiet",
    "--locked",
    "-p",
    "project-x-protocol",
    "--example",
    "export-schema",
  ],
  {
    encoding: "utf8",
    env: {
      ...process.env,
      CARGO_HOME: new URL("../.cache/cargo", import.meta.url).pathname,
    },
  },
);
const schema = JSON.parse(raw);
// Schemars uint8 is a nonstandard format. Preserve explicit numeric bounds;
// remove this annotation only, never disable Ajv strictness for unknown formats.
if (
  schema.properties.version.format !== "uint8" ||
  schema.properties.version.minimum !== 0 ||
  schema.properties.version.maximum !== 255
)
  throw new Error("Schema profile changed");
delete schema.properties.version.format;
const types = await compile(schema, "InputRequest", {
  bannerComment:
    "/* Generated by scripts/generate-bindings.mjs; do not edit. */",
});
const ajv = new Ajv({ code: { source: true, esm: true }, strict: true });
const validate = ajv.compile(schema);
const outputs = {
  "schemas/public/input-request.schema.json":
    JSON.stringify(schema, null, 2) + "\n",
  "packages/protocol/src/generated.ts": types,
  "packages/protocol/src/validate.generated.mjs":
    standaloneCode(ajv, validate) + "\n",
  "packages/protocol/src/validate.generated.d.mts":
    "// Generated; do not edit.\nimport type {InputRequest} from './generated.js';\ndeclare const validate: (value:unknown)=>value is InputRequest;\nexport default validate;\n",
};
for (const [file, data] of Object.entries(outputs)) {
  if (process.argv.includes("--check")) {
    if ((await readFile(file, "utf8")) !== data)
      throw new Error("Generated drift: " + file);
  } else {
    await mkdir(dirname(new URL("../" + file, import.meta.url).pathname), {
      recursive: true,
    });
    await writeFile(new URL("../" + file, import.meta.url), data);
  }
}
